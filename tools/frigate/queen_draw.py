def _grid(text: str, w: int, h: int) -> list[list[int]]:
    rows = text.strip("\n").split("\n")
    if len(rows) != h or any(len(r) != w for r in rows):
        raise ValueError(f"grade de {w}x{h} esperada, veio {len(rows[0])}x{len(rows)}")
    return [[0 if c == "." else int(c, 16) for c in r] for r in rows]


def _paste(canvas: list[int], grid: list[list[int]], x0: int, y0: int, mirror: bool = True,
           transparent: bool = False) -> None:
    for dy, row in enumerate(grid):
        for dx, c in enumerate(row):
            if transparent and not c:
                continue
            canvas[(y0 + dy) * W + x0 + dx] = c
            if mirror:
                canvas[(y0 + dy) * W + W - 1 - (x0 + dx)] = c


def _base(mouth: int = 0, tail: int = 0, claw: int = 0) -> list[int]:
    c = [0] * (W * H)
    _paste(c, _grid(BODY, 40, 96), 0, 0)
    if mouth:
        _paste(c, _grid((MAW_HALF, MAW_OPEN)[mouth - 1], 16, 32), 24, 16)
    _paste(c, _grid(TAIL[tail], 16, 16), 24, 96)
    _paste(c, _grid(CLAW[claw], 8, 16), 16, 96)
    return c


def frames() -> dict[int, list[int]]:
    """One full 80x112 canvas per block (each block writes only its own cells)."""
    out = {0xA7E0AA: _base()}
    for addr, m in MOUTH.items():
        out[addr] = _base(mouth=m)
    core = _grid(CORE, 10, 10)
    for addr, (dx, dy) in CORE_DIR.items():
        c = _base(mouth=2)
        _paste(c, core, CX - 5 + 2 * dx, 27 + 2 * dy, mirror=False, transparent=True)
        out[addr] = c
    for addr, pose in CLAWS.items():
        out[addr] = _base(claw=pose)
    for addr, pose in TAILS.items():
        out[addr] = _base(tail=pose)
    return out
